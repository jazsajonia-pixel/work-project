from datetime import datetime
from pathlib import Path
import os, sqlite3

DATABASE_URL=os.getenv('DATABASE_URL')
DB_PATH=Path(os.getenv('GSCHPT_DB_PATH','/tmp/gschpt.db' if os.getenv('VERCEL') else './storage/gschpt.db'))
if not DATABASE_URL: DB_PATH.parent.mkdir(parents=True,exist_ok=True)
SCHEMA="""
CREATE TABLE IF NOT EXISTS batches (id {auto}, batch_id TEXT UNIQUE NOT NULL, title TEXT NOT NULL DEFAULT '', preparation_date TEXT NOT NULL, incident_date TEXT NOT NULL, incident_time TEXT NOT NULL, location TEXT NOT NULL, period_start TEXT NOT NULL DEFAULT '', period_end TEXT NOT NULL DEFAULT '', operational_info TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'Draft', created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS vehicles (id {auto}, batch_id TEXT NOT NULL REFERENCES batches(batch_id) ON DELETE CASCADE, category TEXT NOT NULL, make TEXT NOT NULL DEFAULT '', vehicle_type TEXT NOT NULL DEFAULT '', model TEXT NOT NULL DEFAULT '', plate_or_sticker TEXT NOT NULL DEFAULT '', chassis_number TEXT NOT NULL DEFAULT '', motor_number TEXT NOT NULL DEFAULT '', color TEXT NOT NULL DEFAULT '', recovery_date TEXT NOT NULL DEFAULT '', recovery_place TEXT NOT NULL DEFAULT '', recovering_unit TEXT NOT NULL DEFAULT '', mode_of_recovery TEXT NOT NULL DEFAULT '', violation TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'For review', driver_name TEXT NOT NULL DEFAULT '', driver_address TEXT NOT NULL DEFAULT '', owner_name TEXT NOT NULL DEFAULT '', owner_address TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '', review_status TEXT NOT NULL DEFAULT 'Needs review');
CREATE TABLE IF NOT EXISTS templates (id {auto}, file_type TEXT NOT NULL, filename TEXT NOT NULL, version TEXT NOT NULL, path TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS generated_reports (id {auto}, batch_id TEXT NOT NULL, file_type TEXT NOT NULL, filename TEXT NOT NULL, path TEXT NOT NULL, template_version TEXT NOT NULL, validation_status TEXT NOT NULL, generated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS uploads (id {auto}, batch_id TEXT NOT NULL REFERENCES batches(batch_id) ON DELETE CASCADE, vehicle_id INTEGER REFERENCES vehicles(id) ON DELETE SET NULL, kind TEXT NOT NULL, filename TEXT NOT NULL, content_type TEXT NOT NULL, path TEXT NOT NULL, primary_image INTEGER NOT NULL DEFAULT 0, document_type TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL);
"""
def _pg(): return bool(DATABASE_URL)
def _sql(query): return query.replace('?','%s') if _pg() else query
def conn():
    if _pg():
        import psycopg
        from psycopg.rows import dict_row
        c=psycopg.connect(DATABASE_URL,row_factory=dict_row,connect_timeout=5)
        for statement in SCHEMA.format(auto='INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').split(';'):
            if statement.strip(): c.execute(statement)
        c.commit(); return c
    c=sqlite3.connect(DB_PATH); c.row_factory=sqlite3.Row; c.execute('PRAGMA foreign_keys=ON'); c.executescript(SCHEMA.format(auto='INTEGER PRIMARY KEY AUTOINCREMENT'))
    migrations={'batches':[('title',"TEXT NOT NULL DEFAULT ''"),('period_start',"TEXT NOT NULL DEFAULT ''"),('period_end',"TEXT NOT NULL DEFAULT ''")],'vehicles':[('mode_of_recovery',"TEXT NOT NULL DEFAULT ''")]}
    for table,cols in migrations.items():
        existing={r[1] for r in c.execute(f'PRAGMA table_info({table})')}
        for name,typ in cols:
            if name not in existing: c.execute(f'ALTER TABLE {table} ADD COLUMN {name} {typ}')
    c.commit(); return c
def now(): return datetime.now().astimezone().isoformat(timespec='seconds')
def rowdict(row): return dict(row) if row else None
def list_rows(query,args=()):
    with conn() as c: return [dict(x) for x in c.execute(_sql(query),args).fetchall()]
def get_row(query,args=()):
    with conn() as c: return rowdict(c.execute(_sql(query),args).fetchone())
def dashboard_snapshot():
    """Read the dashboard in one database session instead of opening seven sessions."""
    with conn() as c:
        total_batches=c.execute(_sql('SELECT COUNT(*) AS c FROM batches')).fetchone()['c']
        draft_reports=c.execute(_sql('SELECT COUNT(*) AS c FROM generated_reports')).fetchone()['c']
        pending_vehicles=c.execute(_sql("SELECT COUNT(*) AS c FROM vehicles WHERE review_status!='Reviewed'")).fetchone()['c']
        recent_batches=[dict(row) for row in c.execute(_sql('SELECT * FROM batches ORDER BY id DESC LIMIT 5')).fetchall()]
        templates=[dict(row) for row in c.execute(_sql('SELECT * FROM templates ORDER BY file_type,id DESC')).fetchall()]
        return {'total_batches':total_batches,'draft_reports':draft_reports,'pending_vehicles':pending_vehicles,'records_review':pending_vehicles,'recent_batches':recent_batches,'templates':templates}
def weekly_batches(period_start, period_end):
    return list_rows("SELECT * FROM batches WHERE COALESCE(NULLIF(period_start,''),incident_date)<=? AND COALESCE(NULLIF(period_end,''),incident_date)>=? ORDER BY incident_date, id",(period_end,period_start))
def batch_vehicles(batch_ids):
    if not batch_ids: return []
    placeholders=','.join('?' for _ in batch_ids)
    return list_rows(f'SELECT * FROM vehicles WHERE batch_id IN ({placeholders}) ORDER BY batch_id,id',tuple(batch_ids))
def batch_uploads(batch_ids):
    if not batch_ids: return []
    placeholders=','.join('?' for _ in batch_ids)
    return list_rows(f'SELECT * FROM uploads WHERE batch_id IN ({placeholders}) ORDER BY batch_id,id',tuple(batch_ids))
def execute(query,args=()):
    with conn() as c:
        statement=_sql(query)
        if _pg() and statement.lstrip().upper().startswith('INSERT') and ' RETURNING ' not in statement.upper():
            cur=c.execute(statement+' RETURNING id',args); result=cur.fetchone()['id']
        else:
            cur=c.execute(statement,args); result=cur.lastrowid
        c.commit(); return result
